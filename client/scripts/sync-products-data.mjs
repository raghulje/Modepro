import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const htmlPath =
  process.argv[2] ||
  path.join(__dirname, "live-snapshots/products.html");
const outPath = path.join(__dirname, "../src/mocks/productsData.ts");

const html = fs.readFileSync(htmlPath, "utf8").replace(/<!--[\s\S]*?-->/g, "");

const tabMeta = [
  { id: "intermediates", label: "Intermediates" },
  { id: "pyridine", label: "Pyridine Derivatives" },
  { id: "thiophene", label: "Thiophene Derivatives" },
];

function extractCas(raw) {
  if (!raw || /^[-—]$/.test(raw.trim())) return "";
  const inner = raw.replace(/^\[|\]$/g, "").trim();
  const m = inner.match(
    /(?:CAS\s*(?:NO\.?|No\.?|no\.?)?\s*:?\s*)?([0-9][0-9\-]+(?:\s*-\s*[0-9\-]+)*)/i
  );
  return m ? m[1].replace(/\s+/g, "") : inner;
}

function normalizeImage(src) {
  if (!src) return "";
  const clean = src.replace(/^\.\//, "").replace(/^\/+/, "");
  return clean.startsWith("images/") ? `/${clean}` : `/images/${clean}`;
}

function parseTable(tableHtml) {
  const groups = [];
  let current = null;
  const rowRe = /<tr class="(title-bg-color|name-str-cas\d)">([\s\S]*?)<\/tr>/gi;
  let m;
  while ((m = rowRe.exec(tableHtml))) {
    if (m[1] === "title-bg-color") {
      const name = m[2].match(/colspan="3">\s*([^<]+)/i)?.[1]?.trim() ?? "";
      current = { name, products: [] };
      groups.push(current);
    } else if (current) {
      const row = m[2];
      const src = row.match(/<img[^>]+src="([^"]+)"/i)?.[1];
      const name = row.match(/data-label="Name">\s*([^<]+)/i)?.[1]?.trim() ?? "";
      const casRaw = row.match(/data-label="Cas No\.">\s*([^<]+)/i)?.[1]?.trim() ?? "";
      current.products.push({
        image: normalizeImage(src),
        name,
        casNo: extractCas(casRaw),
      });
    }
  }
  return groups;
}

const TOKEN = '<div class="tab_content';
const parts = html.split(TOKEN);
const tabTables = parts.slice(1, 1 + tabMeta.length).map((chunk) => {
  const end = chunk.indexOf("</table>");
  return end === -1 ? chunk : chunk.slice(0, end + "</table>".length);
});

if (tabTables.length < tabMeta.length) {
  console.error("Expected", tabMeta.length, "tabs, found", tabTables.length);
  process.exit(1);
}

const tabs = tabMeta.map((meta, i) => ({
  id: meta.id,
  label: meta.label,
  groups: parseTable(tabTables[i]),
}));

let totalGroups = 0;
let totalProducts = 0;
for (const tab of tabs) {
  totalGroups += tab.groups.length;
  for (const g of tab.groups) totalProducts += g.products.length;
}

const introMatch = html.match(
  /class="quality-pg-info-text">\s*([^<]+(?:<[^>]+>[^<]*)*?)\s*<\/div>/i
);
const introText = introMatch
  ? introMatch[1]
      .replace(/<[^>]+>/g, "")
      .replace(/&amp;/g, "&")
      .replace(/\s+/g, " ")
      .trim()
  : "We manufacture intermediates for several API's falling under a wide range of therapeutic categories. We also manufacture fine chemicals & Specialty chemicals. We are among the largest manufacturer of thiophene products in India and we have an extensive range of different thiophene compounds.";

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function serialize(obj, indent = 0) {
  const sp = "  ".repeat(indent);
  if (obj === null || obj === undefined) return "undefined";
  if (typeof obj === "string") return `"${esc(obj)}"`;
  if (typeof obj === "number" || typeof obj === "boolean") return String(obj);
  if (Array.isArray(obj)) {
    if (obj.length === 0) return "[]";
    return `[\n${obj.map((v) => sp + "  " + serialize(v, indent + 1)).join(",\n")}\n${sp}]`;
  }
  const entries = Object.entries(obj);
  return `{\n${entries
    .map(([k, v]) => `${sp}  ${k}: ${serialize(v, indent + 1)}`)
    .join(",\n")}\n${sp}}`;
}

const data = {
  banner: { image: "/images/product-banner.jpg", alt: "Products Portfolio" },
  breadcrumb: [
    { label: "HOME", href: "/" },
    { label: "PRODUCTS", href: "/products" },
  ],
  pageTitle: "PRODUCTS PORTFOLIO",
  intro: { title: "Our Products", description: introText },
  tabs,
};

const file = `// Auto-generated by scripts/sync-products-data.mjs — do not edit manually
// Groups: ${totalGroups}, Products: ${totalProducts}

export const productsData = ${serialize(data, 0)};
`;

fs.writeFileSync(outPath, file);
console.log(`Wrote ${outPath}`);
console.log(`Groups: ${totalGroups}, Products: ${totalProducts}`);
for (const t of tabs) {
  console.log(`  ${t.label}: ${t.groups.length} groups, ${t.groups.reduce((n, g) => n + g.products.length, 0)} products`);
}
